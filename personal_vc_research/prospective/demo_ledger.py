"""End-to-end approval/ledger demonstration on an ISOLATED SYNTHETIC database (never the live pilot database).

Run:  python -m prospective.demo_ledger
Writes reports/demo/ (a step log and a monthly v2 report). Every offering, approval and transaction here is fictional.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

import yaml

from . import ledger, portfolio_report
from .core import Ctx

ROOT = Path(__file__).parent
DEMO = ROOT / "data" / "demo"


def _ctx(now: str) -> Ctx:
    cfg = yaml.safe_load((ROOT / "config.yaml").read_text())
    cfg["ledger_mode"] = "demo"
    cfg["paths"].update({"db": "data/demo/demo.sqlite", "private_dir": "data/demo/private", "reports_dir": "reports/demo",
                         "blobs_dir": "data/demo/blobs", "backups_dir": "data/demo/backups"})
    p = ROOT / "demo_config.yaml"
    p.write_text("# GENERATED by demo_ledger.py — synthetic demo configuration\n" + yaml.safe_dump(cfg))
    return Ctx(p, "demo_ledger", now=now, offline=True)


def main() -> None:
    if DEMO.exists():
        shutil.rmtree(DEMO)
    log = []

    def step(c: Ctx, title: str, result) -> None:
        log.append(f"### {c.now()[:10]} — {title}\n\n```json\n{json.dumps(result, indent=1, default=str)}\n```\n")

    c = _ctx("2026-11-02T15:00:00+00:00")
    for oid, cik, name in [("DEMO-A", "0009000001", "Demo Alpha Foods (SYNTHETIC)"), ("DEMO-B", "0009000002", "Demo Beta Labs (SYNTHETIC)"),
                           ("DEMO-B2", "0009000099", "Demo Beta Labs SPV (SYNTHETIC)")]:
        c.con.execute("""INSERT INTO offerings(offering_id, issuer_id, offering_file_number, legal_name, initial_accession, cohort,
            eligibility, first_observed_utc, availability_status, closing_status, deadline_date, security_class)
            VALUES (?,?,?,?,?,?,?,?,?,?,?,?)""", (oid, cik, "020-DEMO", name, "demo-" + oid, "inception", "eligible", c.now(),
                                                  "unknown", "none_reported", "2027-06-30", "safe"))
        c.con.execute("INSERT INTO evidence_packs VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                      (f"PACK-{oid}", oid, "pack_v1", c.now(), c.now(), "demo-sha", "n/a", "[]", 0, "[]", "{}"))
        c.con.execute("""INSERT INTO analysis_runs(offering_id, pack_id, pack_sha256, version_id, prompt_version, schema_version,
            policy_version, adapter, started_utc, finished_utc, status, split) VALUES (?,?,?,?,?,?,?,?,?,?,?,?)""",
                      (oid, f"PACK-{oid}", "demo-sha", "demo_fixture", "n/a", "n/a", "screening_policy_v1", "fixture",
                       c.now(), c.now(), "passes_research_screen" if oid != "DEMO-B2" else "needs_information", "development"))
    c.con.commit()
    step(c, "approval attempted BEFORE policy acknowledgment (must be blocked)",
         ledger.approve(c, offering_id="DEMO-A", amount_usd="500", fee_usd="10", fee_basis="upper_bound", issuer_key_confirmed="CIK9000001",
                        analysis_id=1, min_investment_usd="150", applicable_terms="Crowd SAFE, $8M post-money cap (synthetic)",
                        availability_note="synthetic", contract_document_id=1))
    step(c, "user acknowledges screening policy", ledger.acknowledge_policy(c, "screening", "screening_policy_v1",
                                                                           ledger.SCREENING_POLICY, "SYNTHETIC DEMO acknowledgment"))
    for cik, key in [("0009000001", "CIK9000001"), ("0009000002", "CIK9000002"), ("0009000099", "CIK9000002")]:
        ledger.confirm_issuer(c, cik, key, "synthetic demo mapping (SPV 0009000099 holds only Beta Labs securities)")
    a1 = ledger.approve(c, offering_id="DEMO-A", amount_usd="500", fee_usd="10", fee_basis="upper_bound", issuer_key_confirmed="CIK9000001",
                        analysis_id=1, min_investment_usd="150", applicable_terms="Crowd SAFE, $8M post-money cap (synthetic)",
                        availability_note="synthetic: checked campaign page", contract_document_id=1)
    step(c, "approve $500 + $10 fee upper bound in DEMO-A (pre-start reservation)", a1)
    a2 = ledger.approve(c, offering_id="DEMO-B", amount_usd="900", fee_usd="0", fee_basis="confirmed", issuer_key_confirmed="CIK9000002",
                        analysis_id=2, min_investment_usd="100", applicable_terms="Crowd SAFE, standard-tier $15M cap (synthetic)",
                        availability_note="synthetic", contract_document_id=1)
    step(c, "approve $900 in DEMO-B", a2)
    step(c, "approve $400 in the SPV of the same issuer (shares Beta's $1,200 limit: must be blocked)",
         ledger.approve(c, offering_id="DEMO-B2", amount_usd="400", fee_usd="0", fee_basis="confirmed", issuer_key_confirmed="CIK9000002",
                        analysis_id=3, min_investment_usd="100", applicable_terms="SPV units (synthetic)", availability_note="synthetic",
                        contract_document_id=1, override_rationale="synthetic override of needs_information"))
    step(c, "budget after two reservations", ledger.current_state(c).__dict__ | {"active_reservations": "omitted"})
    c._now = "2026-11-05T15:00:00+00:00"
    inv = ledger.record_event(c, event_type="investment_submitted", offering_id="DEMO-A", effective_date="2026-11-05", amount_usd="500",
                              fee_usd="8.50", approval_id=a1["approval_id"], external_ref="DEMO-CONF-0001", security="crowd_safe",
                              verification_status="platform_confirmation", note="SYNTHETIC")
    step(c, "user invested manually on the platform; confirmation imported (starts the annual clock)", inv)
    step(c, "same confirmation imported twice (idempotent)",
         ledger.record_event(c, event_type="investment_submitted", offering_id="DEMO-A", effective_date="2026-11-05", amount_usd="500",
                             fee_usd="8.50", approval_id=a1["approval_id"], external_ref="DEMO-CONF-0001"))
    step(c, "finalized", ledger.record_event(c, event_type="investment_finalized", offering_id="DEMO-A", effective_date="2026-11-20",
                                             related_event_id=inv["event_id"], external_ref="DEMO-FINAL-0001"))
    step(c, "budget: reservation consumed, no double count", {k: v for k, v in ledger.current_state(c).__dict__.items()
                                                              if k != "active_reservations"})
    c._now = "2026-11-25T15:00:00+00:00"
    step(c, "DEMO-B reservation canceled by the user (released)", ledger.release_reservation(c, a2["approval_id"], "decided not to invest"))
    step(c, "out-of-policy actual transaction (no approval, above issuer limit) recorded truthfully and flagged",
         ledger.record_event(c, event_type="investment_submitted", offering_id="DEMO-B", effective_date="2026-11-25", amount_usd="1500",
                             external_ref="DEMO-CONF-0002", security="crowd_safe", note="SYNTHETIC breach example"))
    c._now = "2027-12-01T15:00:00+00:00"
    step(c, "cash distribution (does not restore budget)",
         ledger.record_event(c, event_type="cash_distribution", offering_id="DEMO-A", effective_date="2027-12-01", amount_usd="25",
                             related_event_id=inv["event_id"], external_ref="DEMO-DIST-1", verification_status="document_verified"))
    step(c, "budget in the second period (P2 starts 2027-11-05)", {k: v for k, v in ledger.current_state(c).__dict__.items()
                                                                   if k != "active_reservations"})
    step(c, "positions", ledger.positions(c))
    rep = portfolio_report.monthly_v2(c)
    out = ROOT / "reports" / "demo" / "demo_ledger_steps.md"
    out.write_text("# SYNTHETIC approval/ledger demonstration (isolated demo database)\n\nAll offerings, amounts and confirmations "
                   "are fictional. The live pilot database is not touched.\n\n" + "\n".join(log))
    print(json.dumps({"steps": str(out), "monthly_report": rep}, indent=1))


if __name__ == "__main__":
    main()
